"""Turn a Vial keyboard definition into the C header the firmware serves.

The format is Vial's own (util/vial_generate_definition.py): the JSON is
minified and XZ-compressed, and the firmware only serves the compressed bytes
in 32-byte pages. Decompression happens in the Vial GUI, not on the 8051.

Usage:
    python3 utils/vial_generate_definition.py vial.json vial_definition.h
"""

import json
import lzma
import sys


def main():
    if len(sys.argv) != 3:
        print("usage: vial_generate_definition.py path-to-vial.json path-to-output.h")
        return 1

    with open(sys.argv[1], encoding="utf-8") as inf:
        data = json.dumps(json.load(inf), separators=(",", ":")).strip()

    compressed = lzma.compress(data.encode("utf-8"))

    with open(sys.argv[2], "w", encoding="utf-8") as outf:
        outf.write("#pragma once\n\n")
        outf.write("#include <stdint.h>\n\n")
        outf.write("// Generated by utils/vial_generate_definition.py from vial.json.\n")
        outf.write("// clang-format off\n")
        outf.write("static const uint8_t __code keyboard_definition[] = {\n")
        for i in range(0, len(compressed), 12):
            chunk = ", ".join("0x{:02X}".format(b) for b in compressed[i : i + 12])
            outf.write("    " + chunk + ",\n")
        outf.write("};\n")
        outf.write("// clang-format on\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
